-- 4. CONSULTAS DE VALIDAÇÃO E RELATÓRIOS (SELECTS COM JOINS)
-- ----------------------------------------------------------------------------

-- Consulta 1: Extrato Consolidado de Clientes (Pessoa Física) com Carteira e Saldo
SELECT 
    u.ID_USUARIO,
    u.NM_COMPLETO,
    u.NR_CPF,
    u.DS_EMAIL,
    u.DS_MODO_INTERFACE,
    u.FL_KYC_APROVADO,
    u.VL_LIMITE_MENSAL,
    c.DS_ENDERECO_DIGITAL,
    c.VL_SALDO_DISPONIVEL_BRL
FROM TB_USUARIO u
INNER JOIN TB_CARTEIRA c ON u.ID_CARTEIRA = c.ID_CARTEIRA
ORDER BY u.ID_USUARIO;

-- Consulta 2: Posição Patrimonial em Criptoativos por Carteira e Usuário
SELECT 
    u.NM_COMPLETO AS CLIENTE,
    c.DS_ENDERECO_DIGITAL AS CARTEIRA,
    a.CD_SIGLA AS ATIVO,
    a.NM_CRIPTOATIVO AS NOME_CRIPTO,
    p.QT_TOTAL AS QUANTIDADE,
    a.VL_PRECO_ATUAL_BRL AS COTACAO_ATUAL_BRL,
    ROUND(p.QT_TOTAL * a.VL_PRECO_ATUAL_BRL, 2) AS VALOR_TOTAL_BRL
FROM TB_POSICAO_CRIPTO p
INNER JOIN TB_CARTEIRA c ON p.ID_CARTEIRA = c.ID_CARTEIRA
INNER JOIN TB_USUARIO u ON c.ID_CARTEIRA = u.ID_CARTEIRA
INNER JOIN TB_CRIPTOATIVO a ON p.ID_CRIPTOATIVO = a.ID_CRIPTOATIVO
WHERE p.QT_TOTAL > 0
ORDER BY VALOR_TOTAL_BRL DESC;

-- Consulta 3: Histórico de Transações Detalhado com Ativo e Carteira Vinculada
SELECT 
    t.ID_TRANSACAO,
    t.DH_TRANSACAO,
    t.TP_TRANSACAO,
    t.ST_TRANSACAO,
    NVL(a.CD_SIGLA, 'FIAT (BRL)') AS ATIVO,
    t.QT_CRIPTO,
    t.VL_COTACAO_MOMENTO,
    t.VL_MOVIMENTADO_BRL,
    t.VL_TAXA_OPERACAO,
    c.DS_ENDERECO_DIGITAL AS CARTEIRA_ORIGEM
FROM TB_TRANSACAO t
INNER JOIN TB_CARTEIRA c ON t.ID_CARTEIRA = c.ID_CARTEIRA
LEFT JOIN TB_CRIPTOATIVO a ON t.ID_CRIPTOATIVO = a.ID_CRIPTOATIVO
ORDER BY t.DH_TRANSACAO DESC;

-- Consulta 4: Governança Corporativa - Empresas, Usuário Master e Seus Guardiões
SELECT 
    e.DS_RAZAO_SOCIAL AS EMPRESA,
    e.NR_CNPJ AS CNPJ,
    u_master.NM_COMPLETO AS USUARIO_MASTER,
    u_guard.NM_COMPLETO AS GUARDIAO_DESIGNADO,
    g.DT_NOMEACAO,
    g.FL_ATIVO AS GUARDIAO_ATIVO
FROM TB_EMPRESA e
INNER JOIN TB_USUARIO u_master ON e.ID_USUARIO_MASTER = u_master.ID_USUARIO
INNER JOIN TB_GUARDIAO g ON e.ID_EMPRESA = g.ID_EMPRESA
INNER JOIN TB_USUARIO u_guard ON g.ID_USUARIO = u_guard.ID_USUARIO
ORDER BY e.DS_RAZAO_SOCIAL, u_guard.NM_COMPLETO;

-- Consulta 5: Relatório de Cofres Temporais (HODL) e Prazos de Liberação
SELECT 
    cof.ID_COFRE,
    u.NM_COMPLETO AS TITULAR,
    cof.NM_OBJETIVO,
    a.CD_SIGLA AS ATIVO,
    cof.QT_BLOQUEADA,
    cof.DT_CRIACAO,
    cof.DT_LIBERACAO,
    CASE 
        WHEN TRUNC(SYSDATE) >= cof.DT_LIBERACAO THEN 'LIBERADO PARA RESGATE'
        ELSE 'BLOQUEADO EM CARÊNCIA'
    END AS STATUS_TEMPORAL,
    cof.ST_COFRE
FROM TB_COFRE_TEMPORAL cof
INNER JOIN TB_CARTEIRA c ON cof.ID_CARTEIRA = c.ID_CARTEIRA
INNER JOIN TB_USUARIO u ON c.ID_CARTEIRA = u.ID_CARTEIRA
INNER JOIN TB_CRIPTOATIVO a ON cof.ID_CRIPTOATIVO = a.ID_CRIPTOATIVO
ORDER BY cof.DT_LIBERACAO ASC;

-- Consulta 6: Painel Gamificado de Educação - Aulas Concluídas e XP Acumulado
SELECT 
    u.NM_COMPLETO AS ALUNO,
    COUNT(CASE WHEN p.FL_CONCLUIDA = 'S' THEN 1 END) AS AULAS_CONCLUIDAS,
    NVL(SUM(CASE WHEN p.FL_CONCLUIDA = 'S' THEN au.QT_XP_RECOMPENSA ELSE 0 END), 0) AS TOTAL_XP_GANHO
FROM TB_USUARIO u
LEFT JOIN TB_PROGRESSO_AULA p ON u.ID_USUARIO = p.ID_USUARIO
LEFT JOIN TB_AULA au ON p.ID_AULA = au.ID_AULA
GROUP BY u.ID_USUARIO, u.NM_COMPLETO
ORDER BY TOTAL_XP_GANHO DESC;

